// Writes THIRD-PARTY-NOTICES.md: the licence (and any NOTICE file) of every
// package that can end up in public/build, which ships in the Composer
// package. Run by `npm run build`, so it follows the dependencies.
//
// It lists every production dependency, which is a little more than the
// bundler keeps. Listing one too many is harmless; missing one is not.

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;

const paths = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' })
    .split('\n')
    .filter((path) => path.includes('/node_modules/'));

const packages = new Map();

for (const path of paths) {
    const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
    const id = `${pkg.name}@${pkg.version}`;

    if (packages.has(id)) {
        continue;
    }

    const files = readdirSync(path).filter((file) => /^(licen[cs]e|copying|notice)/i.test(file)).sort();
    const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;

    packages.set(id, {
        id,
        license: typeof pkg.license === 'string' ? pkg.license : pkg.license?.type,
        repository: repository?.replace(/^git\+/, '').replace(/\.git$/, ''),
        texts: files.map((file) => ({ file, text: readFileSync(join(path, file), 'utf8').trim() })),
    });
}

const sorted = [...packages.values()].sort((a, b) => a.id.localeCompare(b.id));

const sections = sorted.map(({ id, license, repository, texts }) => {
    const lines = [`## ${id}`, '', `License: ${license ?? 'see below'}${repository ? `  \nSource: ${repository}` : ''}`];

    if (texts.length === 0) {
        lines.push('', 'The package does not include a licence file. Its licence is as declared above; the full text is at its source.');
    }

    for (const { file, text } of texts) {
        lines.push('', `### ${file}`, '', '```', text, '```');
    }

    return lines.join('\n');
});

writeFileSync(
    join(root, 'THIRD-PARTY-NOTICES.md'),
    [
        '# Third-party notices',
        '',
        'The compiled JavaScript in `public/build` includes the open-source packages below. Their licences and notices are reproduced here as those licences require. Popcorn itself is MIT licensed; see `LICENSE`.',
        '',
        'This file is generated by `scripts/third-party-notices.mjs` when the assets are built. Do not edit it by hand.',
        '',
        ...sections.flatMap((section) => [section, '']),
    ].join('\n'),
);

console.log(`THIRD-PARTY-NOTICES.md: ${sorted.length} packages`);
